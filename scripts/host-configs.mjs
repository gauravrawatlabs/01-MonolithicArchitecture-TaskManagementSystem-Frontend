// Turns deploy/security-headers.json (the ONE source of the security headers, Phase 16) into the configuration
// format of each hosting option, so the hosts can never drift apart.
//
//   node scripts/host-configs.mjs nginx [--api-origin https://api.example.com]   → stdout (Docker, VM nginx)
//   node scripts/host-configs.mjs static --api-origin <origin> --out dist         → writes the static-host files:
//        web.config               IIS / Azure App Service (Windows)
//        staticwebapp.config.json Azure Static Web Apps
//        _headers + _redirects    Netlify (also Cloudflare Pages)
//        vercel.json              Vercel (deploy the dist folder)
//
// Without --api-origin the nginx output keeps the placeholder ${API_ORIGIN} (substituted at container start-up).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// A plain path (not a URL object): test environments such as jsdom replace the global URL class, which
// node:fs then rejects.
const HEADERS_FILE = path.join(
  path.dirname(fileURLToPath(import.meta.url)),
  '..',
  'deploy',
  'security-headers.json',
);

/** Cache rules shared by every host: hashed assets forever, the runtime config and the page never stale. */
export const CACHE = {
  assets: 'public, max-age=31536000, immutable',
  config: 'no-store',
  page: 'no-cache',
};

/** The recommended headers, with {API_ORIGIN} replaced by `apiOrigin`. */
export function securityHeaders(apiOrigin) {
  const raw = JSON.parse(readFileSync(HEADERS_FILE, 'utf8'));
  return Object.fromEntries(
    Object.entries(raw)
      .filter(([name]) => !name.startsWith('_'))
      .map(([name, value]) => [name, value.replace('{API_ORIGIN}', apiOrigin)]),
  );
}

/** nginx: one `add_header … always;` per header (include it in EVERY location that adds headers). */
export function nginxHeaders(apiOrigin = '${API_ORIGIN}') {
  return (
    Object.entries(securityHeaders(apiOrigin))
      .map(([name, value]) => `add_header ${name} "${value.replaceAll('"', '\\"')}" always;`)
      .join('\n') + '\n'
  );
}

const xml = (value) =>
  value
    .replaceAll('&', '&amp;')
    .replaceAll('"', '&quot;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;');

/** IIS / Azure App Service (Windows). Needs the IIS URL Rewrite module (installed on App Service). */
export function iisWebConfig(apiOrigin) {
  const headers = Object.entries(securityHeaders(apiOrigin))
    .map(([name, value]) => `        <add name="${xml(name)}" value="${xml(value)}" />`)
    .join('\n');
  const cache = (location, control) => `  <location path="${location}">
    <system.webServer>
      <httpProtocol>
        <customHeaders>
          <add name="Cache-Control" value="${control}" />
        </customHeaders>
      </httpProtocol>
    </system.webServer>
  </location>`;
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/host-configs.mjs from deploy/security-headers.json. Do not edit by hand. -->
<configuration>
  <system.webServer>
    <rewrite>
      <rules>
        <!-- Client-side routes (/projects/7, /settings/account …) are served index.html. -->
        <rule name="SPA fallback" stopProcessing="true">
          <match url=".*" />
          <conditions logicalGrouping="MatchAll">
            <add input="{REQUEST_FILENAME}" matchType="IsFile" negate="true" />
            <add input="{REQUEST_FILENAME}" matchType="IsDirectory" negate="true" />
          </conditions>
          <action type="Rewrite" url="/index.html" />
        </rule>
      </rules>
    </rewrite>
    <httpProtocol>
      <customHeaders>
        <remove name="X-Powered-By" />
${headers}
      </customHeaders>
    </httpProtocol>
  </system.webServer>
${cache('assets', CACHE.assets)}
${cache('config.js', CACHE.config)}
${cache('index.html', CACHE.page)}
</configuration>
`;
}

/** Azure Static Web Apps (read from the deployed folder). */
export function azureStaticWebAppsConfig(apiOrigin) {
  return `${JSON.stringify(
    {
      navigationFallback: {
        rewrite: '/index.html',
        exclude: ['/assets/*', '/config.js', '/favicon.svg'],
      },
      globalHeaders: securityHeaders(apiOrigin),
      routes: [
        { route: '/assets/*', headers: { 'Cache-Control': CACHE.assets } },
        { route: '/config.js', headers: { 'Cache-Control': CACHE.config } },
        { route: '/index.html', headers: { 'Cache-Control': CACHE.page } },
      ],
    },
    null,
    2,
  )}\n`;
}

/** Netlify (and Cloudflare Pages): _headers and _redirects in the published folder. */
export function netlifyHeaders(apiOrigin) {
  const block = (pattern, headers) =>
    `${pattern}\n${Object.entries(headers)
      .map(([name, value]) => `  ${name}: ${value}`)
      .join('\n')}\n`;
  return [
    '# Generated by scripts/host-configs.mjs from deploy/security-headers.json. Do not edit by hand.',
    block('/*', { ...securityHeaders(apiOrigin), 'Cache-Control': CACHE.page }),
    block('/assets/*', { 'Cache-Control': CACHE.assets }),
    block('/config.js', { 'Cache-Control': CACHE.config }),
  ].join('\n');
}
export const netlifyRedirects = () =>
  '# Client-side routes are served index.html (status 200 = rewrite).\n/*  /index.html  200\n';

/** Vercel: deploy the dist folder (the file must sit at the root of what is deployed). */
export function vercelConfig(apiOrigin) {
  const list = (headers) => Object.entries(headers).map(([key, value]) => ({ key, value }));
  return `${JSON.stringify(
    {
      rewrites: [{ source: '/(.*)', destination: '/index.html' }],
      headers: [
        {
          source: '/(.*)',
          headers: list({ ...securityHeaders(apiOrigin), 'Cache-Control': CACHE.page }),
        },
        { source: '/assets/(.*)', headers: list({ 'Cache-Control': CACHE.assets }) },
        { source: '/config.js', headers: list({ 'Cache-Control': CACHE.config }) },
      ],
    },
    null,
    2,
  )}\n`;
}

/** Writes every static-host file into `outDir`. */
export function writeStaticHostFiles(apiOrigin, outDir) {
  const files = {
    'web.config': iisWebConfig(apiOrigin),
    'staticwebapp.config.json': azureStaticWebAppsConfig(apiOrigin),
    _headers: netlifyHeaders(apiOrigin),
    _redirects: netlifyRedirects(),
    'vercel.json': vercelConfig(apiOrigin),
  };
  for (const [name, content] of Object.entries(files))
    writeFileSync(path.join(outDir, name), content);
  return Object.keys(files);
}

function originOf(url) {
  const parsed = new URL(url);
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:')
    throw new Error(`Not an http(s) URL: ${url}`);
  return parsed.origin;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const [target, ...rest] = process.argv.slice(2);
  const option = (name) => {
    const index = rest.indexOf(name);
    return index === -1 ? undefined : rest[index + 1];
  };
  const apiOrigin = option('--api-origin');

  if (target === 'nginx') {
    process.stdout.write(apiOrigin ? nginxHeaders(originOf(apiOrigin)) : nginxHeaders());
  } else if (target === 'static') {
    const source = apiOrigin ?? process.env.VITE_API_BASE_URL;
    if (!source) {
      console.error(
        'static: pass --api-origin <origin> or set VITE_API_BASE_URL (the API the CSP must allow).',
      );
      process.exit(1);
    }
    const written = writeStaticHostFiles(originOf(source), option('--out') ?? 'dist');
    console.log(`Static-host files for API ${originOf(source)}: ${written.join(', ')}`);
  } else {
    console.error(
      'Usage: node scripts/host-configs.mjs nginx [--api-origin <origin>]\n' +
        '       node scripts/host-configs.mjs static [--api-origin <origin>] [--out dist]',
    );
    process.exit(1);
  }
}
